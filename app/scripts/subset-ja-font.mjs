#!/usr/bin/env node
/**
 * Japanese font subset — `npm run fonts:ja` (also runs in `npm run build`).
 *
 * Noto Sans JP is 124 files / 5.3 MB. This script ships only the pieces the
 * site needs:
 *   1. collects every character in the Japanese words of src/data/words.ts
 *      (the word, and its example sentence) plus any Japanese in src/content;
 *   2. picks the @fontsource-variable/noto-sans-jp slices whose unicode-range
 *      covers those characters (Latin slices are skipped: Latin text uses
 *      Source Sans 3);
 *   3. copies just those .woff2 files to public/fonts/noto-sans-jp/ (removing
 *      stale ones) and writes src/styles/ja-font.css with their @font-face
 *      rules.
 * Any character outside the shipped slices falls back to the reader's system
 * Japanese font, so nothing ever shows as a box. Re-run after adding words.
 *
 * Needs a runtime that can import .ts (Node ≥ 22.6 with
 * --experimental-strip-types, or Bun).
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(fileURLToPath(import.meta.url), "..", "..");
const require = createRequire(import.meta.url);
const pkgDir = join(require.resolve("@fontsource-variable/noto-sans-jp/package.json"), "..");
const outDir = join(root, "public/fonts/noto-sans-jp");
const cssOut = join(root, "src/styles/ja-font.css");

// Kana, kanji, CJK punctuation, full-width forms.
const JA = /[　-ヿ㐀-䶿一-鿿豈-﫿＀-￯]/u;

const { words } = await import(pathToFileURL(join(root, "src/data/words.ts")).href);
const text = [];
for (const w of words) {
  if (w.language !== "ja") continue;
  text.push(w.word, w.example?.text ?? "");
}
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".ts")) text.push(readFileSync(p, "utf8"));
  }
}
walk(join(root, "src/content"));
const chars = new Set([...text.join("")].filter((c) => JA.test(c)));
const codes = [...chars].map((c) => c.codePointAt(0));

// Parse the slices: file name + unicode ranges.
const css = readFileSync(join(pkgDir, "wght.css"), "utf8");
const slices = [...css.matchAll(/url\(\.\/files\/([^)]+)\)[^;]*;\s*unicode-range:\s*([^;]+);/g)].map((m) => ({
  file: m[1],
  ranges: m[2].split(",").map((r) => {
    const [a, b] = r.trim().replace(/^U\+/i, "").split("-");
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  }),
  rangeText: m[2].trim(),
}));
const picked = slices.filter(
  (s) => !/latin|cyrillic|vietnamese/.test(s.file) && codes.some((c) => s.ranges.some(([a, b]) => c >= a && c <= b)),
);

mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (!picked.some((s) => s.file === f)) rmSync(join(outDir, f));
let bytes = 0;
for (const s of picked) {
  copyFileSync(join(pkgDir, "files", s.file), join(outDir, s.file));
  bytes += statSync(join(outDir, s.file)).size;
}
if (!existsSync(join(outDir, "LICENSE"))) copyFileSync(join(pkgDir, "LICENSE"), join(outDir, "LICENSE"));

const header = `/* GENERATED by scripts/subset-ja-font.mjs — do not edit by hand.
   Noto Sans JP (SIL Open Font License 1.1, public/fonts/noto-sans-jp/LICENSE).
   ${chars.size} Japanese characters in use → ${picked.length} of ${slices.length} slices, ${Math.round(bytes / 1024)} KB. */
`;
const faces = picked
  .map(
    (s) => `@font-face {
  font-family: "Noto Sans JP Variable";
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  src: url("/fonts/noto-sans-jp/${s.file}") format("woff2-variations");
  unicode-range: ${s.rangeText};
}`,
  )
  .join("\n");
mkdirSync(join(root, "src/styles"), { recursive: true });
writeFileSync(cssOut, header + faces + "\n");
console.log(`fonts:ja — ${chars.size} characters, ${picked.length} slices, ${Math.round(bytes / 1024)} KB → public/fonts/noto-sans-jp/`);
